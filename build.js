// Compiles app.jsx into app.js, which is what index.html actually loads.
//
// The app used to ship Babel to the browser and compile app.jsx on every
// single launch: 2.3MB of compiler, then ~120KB of JSX parsed and
// transformed before anything appeared on screen. Measured cold starts were
// 1.4s on a laptop and 4.9s on a phone with an older processor - long enough
// to read as "the app doesn't work" before it has even drawn. Compiling here
// instead makes the browser's job a plain <script> tag.
//
// Run this after ANY change to app.jsx:
//
//     node build.js
//
// It needs nothing installed: it borrows the Babel that already lives in
// vendor/ (the same compiler the browser used to download), so the build
// works offline and on a machine with no npm.
//
// `targets` matters as much as the speed: the browser no longer compiles
// anything, so whatever lands in app.js is parsed as-is by Safari on
// whatever iPhone this runs on. Compiling down to an older baseline means a
// modern syntax feature can never turn the app into a blank screen there.

const fs = require('fs');
const path = require('path');
const Babel = require(path.join(__dirname, 'vendor', 'babel.js'));

const SRC = path.join(__dirname, 'app.jsx');
const OUT = path.join(__dirname, 'app.js');

const source = fs.readFileSync(SRC, 'utf8');
const stamp = new Date().toISOString().slice(0, 16).replace('T', ' ') + ' UTC';

let code;
try {
  code = Babel.transform(source, {
    filename: 'app.jsx',
    presets: [
      ['env', { targets: { safari: '12', chrome: '70' }, modules: false }],
      ['react', { runtime: 'classic' }],
    ],
    compact: false,
  }).code;
} catch (e) {
  console.error('\napp.jsx did not compile - app.js was NOT written:\n');
  console.error(e.message);
  process.exit(1);
}

const header = `// Generated from app.jsx by build.js - do not edit this file.\n`
  + `// Edit app.jsx and run: node build.js\n`
  + `window.__BUILD__ = ${JSON.stringify(stamp)};\n`;

fs.writeFileSync(OUT, header + code);
console.log(`app.js written - ${(code.length / 1024).toFixed(0)}KB, build ${stamp}`);
